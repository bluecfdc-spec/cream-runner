/* ---- 미세조정 전용 파일 (game.js보다 먼저 로드되어야 한다) --------------------------------
   game.js 안의 기본값을 window.* 로 덮어쓰는 곳이다. 여기에 값이 있으면 이 값이 이기고,
   이 파일을 지우면 game.js의 기본값으로 돌아간다. 숫자만 바꾸는 조정을 할 때마다 76KB짜리
   game.js를 통째로 다시 올리지 않으려고 만든 파일이라, "지금 실제로 적용되고 있는 값"은
   항상 여기를 먼저 봐야 한다.
   ------------------------------------------------------------------------------------------ */

/* ---- 점수 구간 돌파(1,000 / 5,000 / 10,000점) 축하 이미지 ---- */

// 폭: #app 높이 대비 비율. game.js 기본값 0.372에서 30% 확대한 값.
window.MILESTONE_SIZE_FRAC = 0.4836;

// 위에서 내려온 거리: #app 높이 대비. 커진 크기에서도 팝업 확대(1.14배)와 마지막에 살짝
// 떠오르는 구간까지 전부 화면 안에 들어오도록 0.09에서 내렸다.
window.MILESTONE_TOP_FRAC = 0.11;

// 왼쪽 여백: #app 폭 대비. 캐릭터 뒤(왼쪽 끝, 0.025)에서 화면 X축 정중앙으로 옮긴 값이다.
// #app은 항상 16:9라서 이미지 폭 = SIZE_FRAC * appH = SIZE_FRAC * 9/16 * appW 이고,
// 가운데 정렬은 LEFT = (1 - SIZE_FRAC * 9/16) / 2 = (1 - 0.27203) / 2 = 0.36399 이다.
// => SIZE_FRAC을 바꾸면 이 값도 같은 식으로 다시 계산해야 가운데에 그대로 남는다.
window.MILESTONE_LEFT_FRAC = 0.364;
