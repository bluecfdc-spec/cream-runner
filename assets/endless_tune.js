// ============================================================================
//  무한질주 모드 설정값  (endless.html 에서만 읽는다)
// ============================================================================
//  이 파일은 무한질주 페이지에서만 로드된다. 본 게임(index.html)은 이 파일을
//  아예 읽지 않으므로, 여기서 뭘 바꿔도 본 게임에는 절대 영향이 없다.
//
//  난이도가 마음에 안 들면 아래 숫자 세 개만 고치면 된다.
//  고친 뒤 10분쯤 기다리거나 브라우저 새로고침을 몇 번 하면 반영된다.
// ============================================================================

// 무한질주 모드 스위치. 이게 true일 때만 아래 값들이 쓰인다.
window.ENDLESS_MODE = true;

// ---------------------------------------------------------------------------
//  1) 시작 난이도
// ---------------------------------------------------------------------------
//  본 게임은 아주 천천히 시작해서 서서히 빨라지지만, 무한질주는 "처음부터 빠르게"가
//  컨셉이라 중반 속도에서 바로 시작한다.
//
//  3.6 = ?hard 테스트 서버와 똑같은 시작 속도 (본 게임 2분 20초 지점)
//  숫자를 내리면 시작이 느긋해지고, 올리면 처음부터 더 빡세진다.
window.ENDLESS_START_MULT = 3.6;

// 시작 시점의 "게임 내 경과 시간"(초). 장애물 종류가 열리는 기준이라
// 140으로 두면 까마귀/쥐가 처음부터 전부 나온다. 웬만하면 건드리지 말 것.
window.ENDLESS_START_SEC = 140;

// ---------------------------------------------------------------------------
//  2) 난이도 천장  ★ 무한질주의 핵심 ★
// ---------------------------------------------------------------------------
//  본 게임은 난이도가 끝없이 올라가서 5분 5초쯤(배수 30~32)이면 사람이 물리적으로
//  피할 수 없는 구간이 나온다. 본 게임은 그 직전(4분 52초)에 왕이 나와서 끝나도록
//  설계돼 있지만, 무한질주는 끝이 없으므로 천장을 씌우지 않으면 5분에 전원 강제
//  사망하는 모드가 되어버린다.
//
//  그래서 이 값에서 난이도가 멈춘다. 속도도, 장애물 간격도, 중력도 전부 여기서 고정.
//  이 뒤로는 아무리 오래 달려도 똑같은 난이도가 유지된다 = 집중력 싸움.
//
//  8.0 = 본 게임 3분 20초 지점의 난이도 (클리어하는 사람들이 무난히 지나는 구간)
//  올리면 더 빡세지고, 내리면 더 오래 버틸 수 있다.
//  ※ 20을 넘기지 말 것. 30 근처는 사람이 못 피하는 영역이다.
//  ※ 이 값에 도달한 뒤부터 아래 8) 악마 패턴이 등장한다.
window.ENDLESS_MAX_MULT = 8.0;

// ---------------------------------------------------------------------------
//  3) 천장까지 올라가는 속도
// ---------------------------------------------------------------------------
//  3초마다 이 배율만큼 난이도가 오른다. (본 게임은 1.04)
//  1.02 = 시작(3.6)에서 천장(8.0)까지 약 2분 걸림
//  1.04로 올리면 약 1분, 1.01로 내리면 약 4분.
window.ENDLESS_RAMP_FACTOR = 1.02;

// ---------------------------------------------------------------------------
//  4) 순위표 (본 게임과 완전히 분리)
// ---------------------------------------------------------------------------
//  무한질주 점수는 'endless' 컬렉션에 따로 쌓인다. 본 게임의 'scores'와 섞이지
//  않으므로 명예의 전당도 완전히 별개다.
window.SCORES_COLLECTION = 'endless';
window.PLAYS_COLLECTION = 'endless_plays';

// ---------------------------------------------------------------------------
//  5) 하드 난이도 즉시 적용
// ---------------------------------------------------------------------------
//  본 게임은 5,000점을 넘겨야 하드 구간(똥이 커지고 쥐 콤보가 잦아짐)에 들어가는데,
//  무한질주는 1점부터 바로 하드다.
//  (본 게임 기본값은 game.js 10,000점 -> assets/tune.js 가 5,000점으로 덮어쓴다)
window.HARD_MODE_SCORE = 1;

// ---------------------------------------------------------------------------
//  6) BGM - 「신나는 질주」 무한 반복
// ---------------------------------------------------------------------------
//  오프닝곡을 「신나는 질주」로 바꾸고 재생목록을 비운다. 그러면 이 곡 하나가
//  끊김 없이 무한 반복되고, "마지막 곡이 끝나는 순간" 등장하도록 되어 있는 왕(보스)이
//  영영 등장하지 않는다. 보스 제거가 곧 BGM 루프인 셈이다.
window.BGM_OPEN = { file: 'dash.mp3', title: '신나는 질주 · music by Claude AI' };
window.BGM_PLAYLIST = [];

// ---------------------------------------------------------------------------
//  7) 흑견 (우리 편)
// ---------------------------------------------------------------------------
//  회피 게이지가 아래 배수만큼 차면 흑견이 등장한다. 크림이 옆에서 같이 달리다가
//  앞에 장애물이 오면 총알처럼 튀어나가 물어서 없애고 돌아온다. 나가는 길과 돌아오는
//  길 모두 물기 때문에 뭉쳐 나온 장애물도 놓치지 않는다. 정해진 마리 수를 잡으면
//  오른쪽으로 달려나가 퇴장한다. 유모차 무적과는 절대 겹치지 않는다.
window.ENDLESS_DOG_SCORE      = 150;   // 한 마리 잡을 때 점수
window.ENDLESS_DOG_KILLS      = 3;     // 몇 마리 잡으면 퇴장하는지
window.ENDLESS_DOG_GAUGE_MULT = 3;     // 유모차 게이지의 몇 배로 차는지 (3 = 유모차의 1/3 빈도)
                                       //   2였을 때 유모차 무적과 너무 자주 겹쳐서 3으로 올렸다.

//  까마귀를 물 수 있는 높이. 흑견 키의 배수다. 흑견은 딱 이 높이까지 뛰어오른다.
//  까마귀는 멀리서 높이 떠 있다가 크림이 앞에서 급강하하므로, 이 값이 곧
//  "얼마나 가까이 내려와야 물 수 있는지"를 정한다.
//    2.0 = 화면 폭 42% 안쪽으로 들어온 까마귀를 잡는다 (기본).
//          실측에서 실제 도약 높이는 흑견 키의 0.8~0.95배 정도로, 개가 새를
//          향해 뛰어오르는 높이로 자연스럽다. 참고로 크림이 단일 점프는 키의 2.7배.
//    1.3 = 거의 코앞까지 내려와야 잡는다 (아슬아슬, 덜 뛴다)
//    3.0 = 더 멀리서 더 높이 뛴다 (개답지 않게 보일 수 있음)
//  똥과 쥐는 항상 지면에 있어서 이 값과 무관하게 언제든 잡힌다.
window.ENDLESS_DOG_REACH      = 2.0;

//  흑견이 까마귀도 물게 할지.
//  까마귀를 물 때는 그 높이까지 뛰어오르고, 뛰는 동안 흑견 그림의 두 번째 프레임
//  (네 발이 다 떠서 몸이 늘어난 자세)으로 고정된다. 그림을 새로 그리지 않고 점프
//  연출을 만든 것이다. false로 두면 똥과 쥐만 잡고 까마귀는 그냥 지나친다.
window.ENDLESS_DOG_CATCH_CROW = true;

//  돌진/복귀 속도 (스크롤 속도의 배수). 올리면 더 총알같아진다.
window.ENDLESS_DOG_DASH       = 2.4;
window.ENDLESS_DOG_BACK       = 3.2;

// ---------------------------------------------------------------------------
//  8) 악마 패턴  (기본은 꺼짐. 최고 속도 도달 후에만 등장)
// ---------------------------------------------------------------------------
//      똥1  ->  똥2  ->  악마(제자리 높은 점프)  ->  까마귀
//
//  정답:  똥1 1단 점프 / 똥2 착지 후 다시 1단 점프 / 악마는 점프하지 말고 아래로
//         통과 / 악마를 지난 직후 까마귀를 점프.
//
//  악마는 "그때 공중에 있으면 죽는다"는 장치다. 악마의 점프 높이는 시간이 아니라
//  x 위치로만 계산되므로 속도와 무관하게 언제나 같은 자리에서 같은 높이로 뜬다.
//
//  ★ 간격은 숫자로 박아두지 않는다 ★
//  game.js 가 스스로 정한 스폰 하한(2단 점프 체공 + 반응 여유 0.21초)을 매번
//  계산해서 그대로 쓴다. 천장(배수 8.0)에서 0.775초 = 화면높이의 1.30배다.
//  2026-09-23 밤에 이 값을 무시하고 직접 0.78~0.90배로 넣었다가 게임이 보장하는
//  간격보다 40% 좁아서 플레이가 불가능했다. 그 실수를 구조적으로 막아둔 것이다.
window.ENDLESS_DEMON = false;           // ★ 운영 기본값: 꺼짐. true 로 바꾸면 공개된다

//  간격 배수. 1.0 = game.js 가 보장하는 최소 간격과 똑같다.
//    1.0 = 표준 (똥2 착지 후 악마까지 여유 375ms)
//    1.2 = 20% 넉넉하게 (더 쉽게)
//    0.9 미만으로는 내리지 말 것 - 게임이 보장하는 공정성 기준을 깨는 구간이다
window.ENDLESS_DEMON_GAP_MULT = 1.0;
//  까마귀 뒤에 강제로 비워두는 구간 (간격 배수). 까마귀를 2단으로 넘은 사람의 착지 자리.
window.ENDLESS_DEMON_TAIL = 1.0;

//  악마 크기 (흑견 키의 배수) 와 제자리 점프 높이 (화면 높이의 배수).
//  0.36 은 크림이 단일 점프(0.40)의 90%다. 0.22 미만으로 내리면 아래로 지나갈 수
//  없게 되므로 절대 내리지 말 것.
window.ENDLESS_DEMON_H = 1.0;
window.ENDLESS_DEMON_HOP = 0.36;

//  패턴이 나오는 간격 (초). 무작위로 이 사이에서 정해진다.
window.ENDLESS_DEMON_WAIT_MIN = 16;
window.ENDLESS_DEMON_WAIT_MAX = 40;

// ---------------------------------------------------------------------------
//  9) 테스트 모드   endless.html?demontest=1
// ---------------------------------------------------------------------------
//  악마와 흑견을 바로, 자주 보기 위한 주소다. 이 주소로만 켜지고, 평소 무한질주
//  페이지에는 아무 영향이 없다.
//    - 처음부터 최고 속도로 시작한다 (악마가 바로 나올 수 있게)
//    - 악마 패턴이 4~8초마다 나온다
//    - 흑견이 계속 소환된다 (회피 게이지를 채우지 않아도 됨)
//    - 점수는 규칙이 허용하지 않는 컬렉션으로 보내므로 순위표에 절대 안 쌓인다
//      (그래서 이 주소에서는 "등록에 실패했어요"가 뜨는 게 정상이다)
(function(){
  try {
    if (!new URLSearchParams(window.location.search).has('demontest')) return;
    window.ENDLESS_DEMON = true;
    window.ENDLESS_START_MULT = window.ENDLESS_MAX_MULT;   // 처음부터 천장
    window.ENDLESS_DEMON_WAIT_MIN = 4;
    window.ENDLESS_DEMON_WAIT_MAX = 8;
    window.ENDLESS_TEST_DOG = true;
    window.SCORES_COLLECTION = 'endless_test';        // 규칙에 없는 이름 = 저장 불가
    window.PLAYS_COLLECTION  = 'endless_test_plays';
  } catch (e) {}
})();
