window.ENDLESS_DOG_CATCH_CROW = true;

//  돌진/복귀 속도 (스크롤 속도의 배수). 올리면 더 총알같아진다.
window.ENDLESS_DOG_DASH       = 2.4;
window.ENDLESS_DOG_BACK       = 3.2;

// ---------------------------------------------------------------------------
//  8) 악마 패턴
// ---------------------------------------------------------------------------
//      똥1  ->  똥2  ->  악마(제자리 높은 점프)  ->  까마귀
//
//  정답:  똥1 1단 점프 / 똥2 착지 후 다시 1단 점프 / 악마는 점프하지 말고 아래로
//         통과 / 악마를 지난 직후 까마귀를 점프.
//
//  ★ 언제 나오는가 ★
//  조건은 점수가 아니라 속도다. 배수가 천장(위 2번)에 닿은 뒤부터 나온다. 지금은
//  처음부터 천장으로 시작하므로, 한 판의 첫 패턴은 FIRST_WAIT 초 뒤에 나오고
//  그 뒤로는 WAIT_MIN ~ WAIT_MAX 초 사이에서 무작위로 반복된다.
//
//  악마는 "그때 공중에 있으면 죽는다"는 장치다. 악마의 점프 높이는 시간이 아니라
//  x 위치로만 계산되므로 속도와 무관하게 언제나 같은 자리에서 같은 높이로 뜬다.
//
//  ★ 간격과 도약 구간은 숫자로 박아두지 않는다 ★
//  세 간격은 역할이 달라서 기준도 다르다. demon_module.js 가 매번 계산하므로,
//  위 2-2)에서 속도와 중력을 바꾸면 이 간격도 자동으로 따라간다.
//    똥1-똥2   점프하고 착지해서 또 점프한다 -> game.js 의 스폰 하한 그대로
//              (2단 점프 체공 + 반응 여유 0.21초)
//    똥2-악마   악마는 점프로 넘는 게 아니라 밑으로 지나간다. 착지해 있기만 하면
//              되므로 점프 하한이 필요 없다 -> 체공 + 0.06초
//    악마-까마귀 까마귀를 뛰려고 누르는 순간 악마가 이미 지나가 있어야 한다
//              -> 1단 점프 거리 + 악마 판정폭에서 역산
//  도약 구간도 악마 크기에서 역산한다. 크기를 얼마로 두든 "겹치는 내내 캐릭터 키보다
//  높이 떠 있다"가 보장된다.
//  2026-09-23 밤에 이 값들을 손으로 박았다가 게임이 보장하는 간격보다 40% 좁아서
//  플레이가 불가능했다. 그 실수를 구조적으로 막아둔 것이다.
