/* ---- 미세조정 전용 파일 (game.js보다 먼저 로드되어야 한다) --------------------------------
   game.js 안의 기본값을 window.* 로 덮어쓰는 곳이다. 여기에 값이 있으면 이 값이 이기고,
   이 파일을 지우면 game.js의 기본값으로 돌아간다. 숫자만 바꾸는 조정을 할 때마다 76KB짜리
   game.js를 통째로 다시 올리지 않으려고 만든 파일이라, "지금 실제로 적용되고 있는 값"은
   항상 여기를 먼저 봐야 한다.
   이 파일은 본 게임과 무한질주가 둘 다 읽는다 (무한질주는 그 뒤에 endless_tune.js 로 일부를
   다시 덮어쓴다).
   ------------------------------------------------------------------------------------------ */

/* ---- 점수 구간 돌파(1,000 / 5,000 / 10,000점) 축하 이미지 ---- */

// 폭: #app 높이 대비 비율. game.js 기본값 0.372에서 30% 확대한 값.
window.MILESTONE_SIZE_FRAC = 0.4836;

// 위에서 내려온 거리: #app 높이 대비. 커진 크기에서도 팝업 확대(1.14배)와 마지막에 살짝
// 떠오르는 구간까지 전부 화면 안에 들어오도록 0.09에서 내렸다.
window.MILESTONE_TOP_FRAC = 0.11;

// 왼쪽 여백: #app 폭 대비. 캐릭터 뒤(왼쪽 끝, 0.025)에서 화면 X축 정중앙으로 옮긴 값이다.
// #app은 항상 16:9라서 이미지 폭 = SIZE_FRAC * appH = SIZE_FRAC * 9/16 * appW 이고,
// 가운데 정렬은 LEFT = (1 - SIZE_FRAC * 9/16) / 2 = (1 - 0.27203) / 2 = 0.36399 이다.
// => SIZE_FRAC을 바꾸면 이 값도 같은 식으로 다시 계산해야 가운데에 그대로 남는다.
window.MILESTONE_LEFT_FRAC = 0.364;

/* ---- 하드 구간(큰 똥 + 뛰는 쥐) 시작 점수 -------------------------------------------------
   game.js 기본값은 10,000점이지만, 5,000점부터 어려워지게 내렸다. 1,000/5,000/10,000점
   돌파 축하 연출은 그대로 셋 다 유지되므로, 5,000점 연출이 곧 "여기서부터 어려워진다"는
   신호가 되고 10,000점 연출은 순수 축하로 남는다.
   점수 페이스에 따라 5,000점은 대략 1분 40초 ~ 2분 25초 지점이다 (난이도 배수 2.2~3.8).
   그 속도에서도 똥+쥐 콤보가 통과 가능한지는 시뮬레이션으로 확인했다 (배수 2 이상 전부 통과).
   ------------------------------------------------------------------------------------------ */
window.HARD_MODE_SCORE = 5000;

/* ---- 하드 구간 난이도 ---------------------------------------------------------------------
   아래 두 값은 실제 코드의 물리식(중력/점프 최고점/콤보 간격/판정 박스)을 그대로 옮긴
   시뮬레이션으로 검증했다. 똥+쥐 콤보가 가장 바짝 붙어 나오는 최악의 경우에 1단/2단/착지 후
   재점프까지 모든 타이밍을 전수 탐색한 결과:
     쥐 도약 1/3   -> 난이도 배수 40까지 통과 가능
     쥐 도약 0.467 -> 배수 30까지 통과 가능   <= 지금 값
     쥐 도약 0.55  -> 배수 20에서 이미 통과 불가능 (넘기면 안 되는 선)
     똥 2.20/2.60  -> 둘 다 배수 30까지. 2.80부터 배수 20으로 급락
   경과 시간 대비 배수는 대략 3분=6, 4분=13.5, 4.5분=20, 5분=29.5, 5.5분=43.6 이다.
   즉 보스가 4분 30초 안에 등장해야 "끝까지 넘을 수 있는 게임"이 된다.
   ------------------------------------------------------------------------------------------ */

// 핑크똥 크기 배수 (하드 구간부터 새로 나오는 것에 적용).
//   1.15(원래) -> 1.38 -> 1.80 -> 2.60. 높이는 화면 높이의 26%로, 캐릭터 키(39%)의 2/3.
//   단일 점프 최고점이 40%라서 한 번 점프로 넘는 데는 여유가 남는다.
window.POOP_HARD_SCALE = 2.60;

// 회색쥐가 화면 가운데에서 깔짝 뛰는 높이 (플레이어 단일 점프 높이 대비).
//   1/3 -> 0.467 (+40%). 쥐 최고점은 화면 높이의 18.7%가 되고, 쥐를 넘으려면 33.7%까지
//   떠야 한다 (단일 점프 최고점 40%의 84%를 쓰는 셈이라 타이밍이 상당히 빡빡해진다).
//   더 올리면 안 되는 이유가 하나 더 있다: 캐릭터 판정 박스는 키의 아래 55%(=화면의 21.5%)
//   만 쓰기 때문에, 쥐 최고점이 그보다 높아지면 서 있는 캐릭터의 머리 위로 지나가서
//   "눈에는 부딪혔는데 안 맞는" 상황이 생긴다.
window.MOUSE_HOP_PEAK_FRAC = 0.467;

/* ---- 쥐 / 까마귀 판정 박스 ----------------------------------------------------------------
   game.js 는 똥에만 판정 축소값을 주고(위쪽 28% + 좌우 36% 제외), 쥐와 까마귀는 기본값
   그대로 두었다. 그래서 세 장애물의 판정이 이렇게 어긋나 있었다:

     똥      그림의 가로 64% x 세로  72%
     쥐              가로 84% x 세로 100%
     까마귀          가로 84% x 세로 100%

   쥐와 까마귀는 그림 세로 전체가 판정이라 똥보다 훨씬 엄격했다. 실제로 그림 파일에는
   투명 여백이 거의 없다(채움률 99~100%)는 것도 확인했으므로, 판정을 줄이는 것은
   "여백을 덜어내는" 수준이 아니라 진짜로 관대하게 만드는 조정이다.

   0.14 / 0.88 = 지금 판정의 가로 86% / 세로 88% 로 줄인다.
   똥 기준(64%/72%)에 비하면 여전히 넉넉한 편이라, 더 줄일 여지도 남아 있다.
   ------------------------------------------------------------------------------------------ */
window.MOUSE_HIT_SIDE_FRAC = 0.14;   // 좌우로 각각 14% 제외 -> 가로 72%
window.MOUSE_HIT_TOP_FRAC  = 0.88;   // 위쪽 12% 제외        -> 세로 88%
window.CROW_HIT_SIDE_FRAC  = 0.14;
window.CROW_HIT_TOP_FRAC   = 0.88;

/* ---- 까마귀 연출과 판정의 어긋남 ----------------------------------------------------------
   까마귀는 그림만 위로 띄워서 급강하하는 것처럼 보이게 하고, 판정 박스는 땅에 고정해 둔다.
   판정이 같이 움직이면 언제 점프해야 하는지 알 수 없어지므로 이건 의도된 설계다.

   문제는 그림이 0으로 내려오는 기준점이 charLeftPx(캐릭터 그림 왼쪽 끝)였다는 것이다.
   캐릭터의 실제 판정 박스는 거기서 46px 오른쪽에 있으므로, 까마귀와 겹쳐 있는 내내
   그림이 판정보다 위에 떠 있었다. 390px 화면에서 실측하면:

     기준점 charLeftPx        -> 겹침 구간에서 최대 15.1px 어긋남 (까마귀 몸통의 1/3)
     기준점 +0.33 캐릭터폭    -> 최대 3.5px

   "머리에 닿지도 않았는데 죽는다"는 체감의 진짜 원인이 이것이었다. 판정 박스를 줄이는
   것만으로는 15.1 -> 13.9px 밖에 안 줄어서 거의 효과가 없다.
   아래 값은 캐릭터 폭 대비 비율이다. 0 으로 두면 예전 동작으로 돌아간다.
   ------------------------------------------------------------------------------------------ */
window.CROW_ARC_ANCHOR_CW = 0.33;

/* ---- 무적 상태에서 장애물/보스를 처치했을 때 주는 점수 ---- */
