//  이렇게 한 이유: 악마 패턴은 천장에 도달한 뒤에만 나오는데, 램프를 두면 그
//  시간(1~2분)을 버티기 전에 죽어서 악마를 볼 수가 없었다.
//
//  8.0 = 천장과 동일 (현재값). 3.6 으로 내리면 예전처럼 서서히 올라간다.
window.ENDLESS_START_MULT = 8.0;

// 시작 시점의 "게임 내 경과 시간"(초). 장애물 종류가 열리는 기준이라
// 140으로 두면 까마귀/쥐가 처음부터 전부 나온다. 웬만하면 건드리지 말 것.
window.ENDLESS_START_SEC = 140;

// ---------------------------------------------------------------------------
//  2) 난이도 천장  ★ 무한질주의 핵심 ★
// ---------------------------------------------------------------------------
//  본 게임은 난이도가 끝없이 올라가서 5분 5초쯤(배수 30~32)이면 사람이 물리적으로
//  피할 수 없는 구간이 나온다. 본 게임은 그 직전(4분 52초)에 왕이 나와서 끝나도록
//  설계돼 있지만, 무한질주는 끝이 없으므로 천장을 씌우지 않으면 5분에 전원 강제
//  사망하는 모드가 되어버린다.
//
//  그래서 이 값에서 난이도가 멈춘다. 아무리 오래 달려도 똑같은 난이도 = 집중력 싸움.
//
//  8.0 = 본 게임 3분 20초 지점의 배수
//  ※ 20을 넘기지 말 것. 30 근처는 사람이 못 피하는 영역이다.
//  ※ 악마 패턴은 이 값에 도달한 뒤부터 나온다. 지금은 1)에서 처음부터 이 값으로
//     시작하므로 첫 프레임부터 조건이 성립한다.
window.ENDLESS_MAX_MULT = 8.0;

// ---------------------------------------------------------------------------
//  2-2) 천장에서의 절대 속도와 중력  ★ 본 게임보다 빠른 구간 ★
// ---------------------------------------------------------------------------
//  game.js 는 스크롤 속도를 MAX_SPEED(화면폭 x 0.945)에서, 중력을 배수 4에서 각각
//  상한에 묶는다. 그래서 원래는 본 게임 후반과 무한질주 천장의 절대 속도와 점프
//  궤적이 완전히 같았다. 무한질주를 본 게임보다 확실히 빡세게 만들려고 둘 다 열었다.
//
//  ★ 두 값은 반드시 같이 움직여야 한다 ★
//  속도 상한만 올리면 화면만 빨라지고 난이도는 그대로다. 장애물 스폰 간격이 픽셀이
//  아니라 "체공시간 + 반응여유 0.21초"라는 시간으로 정해지기 때문에, 속도를 올리면
//  간격도 픽셀로 같이 벌어져서 눌러야 하는 타이밍이 하나도 안 변한다.
//  실제로 어려워지는 건 중력이다. 중력이 커지면 체공이 짧아지고, 그만큼 장애물이
//  시간축에서 촘촘해진다.
//
//  1.2 = 절대 속도를 1.2배로. 369 -> 442 px/s (390px 화면 기준)
window.ENDLESS_SPEED_CAP_MULT = 1.2;
//  6.6 = 중력 상한 배수. 속도 1.2배에 맞춰 역산한 값이다.
//        체공시간을 정확히 1/1.2 로 줄인다 (2단 점프 565ms -> 470ms).
//        그러면 픽셀로 본 점프 궤적과 장애물 간격이 예전과 똑같이 유지되면서,
//        시간축에서만 1.14배 촘촘해진다. (0.21초 반응 여유는 줄이지 않기 때문에
//        1.2배가 아니라 1.14배다. 이 0.21초는 사람 반응한계라 건드리면 안 된다)
//        ※ 이 값을 올리면 점프가 더 짧고 빨라진다. 8 이상은 확인 안 했다.
window.GRAVITY_CAP_MULT = 6.6;

// ---------------------------------------------------------------------------
//  2-3) 똥+쥐 조합 빈도
// ---------------------------------------------------------------------------
//  똥 바로 뒤에 쥐가 붙어 나오는 "조합"의 확률이다. 사람들이 제일 어려워하는 구간이라
//  여기가 사실상 체감 난이도를 정한다.
//  game.js 의 식은 배수가 GRAVITY_CAP_MULT 에서 COMBO_RAMP_MULT 로 갈수록 확률을
//  0.38 에서 DOG_COMBO_CHANCE_MAX 까지 올린다.
//  COMBO_RAMP_MULT 를 천장(8.0)에 맞춰두면, 천장에서의 확률이 정확히
//  DOG_COMBO_CHANCE_MAX 가 된다. 그래서 아래 값이 곧 "천장에서의 조합 확률"이다.
//    0.522 = 예전(0.435)의 1.2배
