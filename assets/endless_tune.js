window.BGM_PLAYLIST = [];

// ---------------------------------------------------------------------------
//  7) 흑견 (우리 편)
// ---------------------------------------------------------------------------
//  크림이 혼자일 때만 흑견 게이지가 찬다. 다 차면 흑견이 나와서 크림이 옆에서 같이
//  달리다가, 앞에 장애물이 오면 총알처럼 튀어나가 물어서 없애고 돌아온다. 나가는
//  길과 돌아오는 길 모두 물기 때문에 뭉쳐 나온 장애물도 놓치지 않는다. 정해진 마리
//  수를 잡으면 오른쪽으로 달려나가 퇴장한다.
//
//  ※ 위 5)에서 시작 목숨이 1이므로, 무한질주에서는 첫 초부터 게이지가 찬다.
//     "혼자 달리는 크림이를 도와주러 오는 친구"가 이 모드의 기본 구성이 된 셈이다.
//  유모차 무적과는 겹치지 않는다. 게이지가 다 찼어도 무적 중이면 끝날 때까지 기다린다.
window.ENDLESS_DOG_SCORE      = 150;   // 한 마리 잡을 때 점수
window.ENDLESS_DOG_KILLS      = 5;     // 몇 마리 잡으면 퇴장하는지
//  유모차 게이지의 몇 배가 필요한지 = 충전 속도의 역수.
//    3   = 유모차의 1/3 속도 (예전값)
//    1.5 = 유모차의 2/3 속도 = 예전보다 정확히 2배 빠름 (현재값)
