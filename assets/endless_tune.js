//  악마 크기 (흑견 키의 배수).
//    1.8 = 기본. 화면(#app)이 가로 띠라 세로가 짧아서, 1.0(흑견 크기)이면 33px밖에
//          안 되고 화면에서 뭔지 알아볼 수 없다.
//    2.6 까지는 도약 구간이 자동으로 늘어나 통과가 보장된다. 그 위는 확인 안 했다.
