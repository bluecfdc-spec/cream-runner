//  유모차 무적이 끝난 뒤 장애물을 몇 개 더 넘기면 흑견이 등장한다. 크림이 옆에서
//  같이 달리다가 앞에 장애물이 오면 총알처럼 튀어나가 물어서 없애고 돌아온다. 나가는
