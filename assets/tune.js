/* ---- 콤보 시험 주소  ?combotest=1&conly=1&cgap=0.58&chop=0.62 ------------------------------
   이 주소에서만 아래 값들을 직접 바꿔볼 수 있다. 일반/무한 어느 페이지에서나 쓸 수 있다.

     &cgap=  똥과 쥐의 간격      (COMBO_GAP_FRAC,     0.40 ~ 0.80)
     &chop=  쥐가 뛰는 높이      (MOUSE_HOP_PEAK_FRAC, 0.30 ~ 0.65)
     &conly=1  똥쥐 콤보만 계속 나오게 (연습/비교용)

   ★ conly=1 이 하는 일 ★
   game.js 의 조합 확률(comboChance)을 1 로 만든다. 무한질주는 난이도가 처음부터 천장이라
   comboChance 가 곧 DOG_COMBO_CHANCE_MAX 이므로, 이 값을 1 로 주면 "똥이 나오면 무조건
   뒤에 쥐가 붙는다". 콤보 하나를 기다리느라 한참 달리지 않아도 되므로 값을 바꿔가며
   비교하기 좋다.
   단 game.js 에 "쥐 바로 뒤에 또 쥐는 안 붙인다"(prevType !== 'dog')는 규칙이 있어서,
   콤보와 콤보 사이에는 장애물이 하나씩 끼어든다. 그래서 '콤보만'이 아니라 '한 번 걸러
   콤보'가 최대치다. 그 규칙은 game.js 안에 있어서 주소로는 못 바꾼다.

   ★ chop 을 0.65 까지만 열어둔 이유 ★
   쥐 도약을 올리면 "혼자 나오는 쥐"도 같이 높이 뛴다. 겹침 구간에서 넘어야 하는 높이가
   이렇게 올라간다 (1단 점프 최고점은 87.8px):
     0.467 -> 69.2px  (1단으로 넘김, 성공 23칸)
     0.550 -> 76.4px  (16칸)
     0.620 -> 82.4px  (10칸, 꽤 빡빡)
     0.700 -> 89.3px  ★1단 점프로는 물리적으로 불가능★
   0.70 부터는 모든 쥐를 2단으로만 넘어야 하는 게임이 되어버린다. 그래서 0.65 에서 막았다.
   (반대로 너무 높이면 쥐가 서 있는 크림이 머리 위로 지나가 그냥 통과되는 문제도 있는데,
    그건 0.78 까지 확인해도 안 생긴다. 도약 정점이 캐릭터보다 오른쪽이기 때문이다)
   ------------------------------------------------------------------------------------------ */
(function(){
  try {
    var q = new URLSearchParams(window.location.search);
    if (!q.has('combotest')) return;
    var v = parseFloat(q.get('cgap'));
    if (isFinite(v)) window.COMBO_GAP_FRAC = Math.min(0.80, Math.max(0.40, v));
    var h = parseFloat(q.get('chop'));
    if (isFinite(h)) window.MOUSE_HOP_PEAK_FRAC = Math.min(0.65, Math.max(0.30, h));
    if (q.get('conly') === '1') window.DOG_COMBO_CHANCE_MAX = 1;
  } catch (e) {}
})();

